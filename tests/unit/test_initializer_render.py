import pytest
import yaml

from dbs_vector.core.model_registry import ModelContract, ModelRegistry
from dbs_vector.core.profile_math import fitting_tiers
from dbs_vector.services.initializer.answers import InitAnswers, KindAnswers
from dbs_vector.services.initializer.kinds import EngineKindRegistry
from dbs_vector.services.initializer.render import (
    build_config_dict,
    dump_config_yaml,
    is_dbs_vector_checkout,
    profile_name_for,
    table_name_for,
    validate_rendered_config,
    workflow_for,
)

BUDGET = 21.0


def _answers(**overrides) -> InitAnswers:
    base = dict(
        engine_name="docs",
        model_key="granite-r2",
        kind_key="document",
        tier_key="medium",
        passage_prefix="",
        query_prefix="",
        db_path="/tmp/lancedb_dbs_vector",
        install_dir="/repo",
        config_path="config.yaml",
        mcp_path=".mcp.json",
        kind=KindAnswers(
            paths=["/tmp/notes"],
            ignore_patterns=[".#*", "*~", "*.tmp", ".DS_Store"],
            exclusion_filters=["excalidraw", "compressed_json"],
        ),
    )
    base.update(overrides)
    return InitAnswers(**base)


def _build(answers: InitAnswers) -> dict:
    contract = ModelRegistry.get(answers.model_key)
    kind = EngineKindRegistry.get(answers.kind_key)
    profile = kind.build_profile(contract, answers.tier_key, BUDGET)
    return build_config_dict(answers, profile, contract, kind)


def test_derived_names():
    assert table_name_for("md-granite") == "md_granite_vault"
    assert workflow_for("md-granite") == "md_granite_search"
    assert profile_name_for("docs", "medium") == "docs-medium"


def test_db_path_is_written_absolute():
    config = _build(_answers())
    assert config["system"]["db_path"] == "/tmp/lancedb_dbs_vector"


def test_engine_block_shape():
    config = _build(_answers())
    engine = config["engines"]["docs"]
    assert engine["model"] == "granite-r2"
    assert engine["mapper_type"] == "document"
    assert engine["chunker_type"] == "document"
    assert engine["table_name"] == "docs_vault"
    assert engine["workflow"] == "docs_search"
    assert engine["tuning_profile"] == "docs-medium"
    assert engine["paths"] == ["/tmp/notes"]


def test_similarity_floor_is_never_written():
    """Floors are deployment-local calibration evidence; a wizard must not
    invent one."""
    config = _build(_answers())
    assert "similarity_floor" not in config["engines"]["docs"]


def test_family_is_never_written():
    """family defaults to mapper_type; emitting it is redundant noise."""
    config = _build(_answers())
    assert "family" not in config["engines"]["docs"]


def test_prefixes_omitted_when_the_contract_carries_none():
    config = _build(_answers(model_key="granite-r2"))
    assert "passage_prefix" not in config["engines"]["docs"]
    assert "query_prefix" not in config["engines"]["docs"]


def test_prefixes_written_when_present():
    config = _build(
        _answers(
            model_key="gemma-bf16",
            tier_key="small",
            passage_prefix="title: none | text: ",
            query_prefix="task: search result | query: ",
        )
    )
    engine = config["engines"]["docs"]
    assert engine["passage_prefix"] == "title: none | text: "
    assert engine["query_prefix"] == "task: search result | query: "


