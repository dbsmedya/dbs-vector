@pytest.mark.parametrize("model_key", ModelRegistry.keys())
def test_every_model_and_fitting_tier_produces_a_valid_config(model_key):
    """The §10 matrix. Task 2 checks derivation INVARIANTS; this checks that
    the resulting config survives the real validator end to end - the two are
    not the same, and only this one catches a rule that derivation does not
    model (engine naming, family, watch, table exclusivity)."""
    contract = ModelRegistry.get(model_key)
    tiers = fitting_tiers(contract)
    assert tiers, f"{model_key} fits no tier - the matrix would be vacuous"
    for tier in tiers:
        answers = _answers(model_key=model_key, tier_key=tier.key)
        config = _build(answers)
        text = dump_config_yaml(config, model_key=model_key, budget_gb=BUDGET)
        validate_rendered_config(text)


def test_a_synthetic_model_also_produces_a_valid_config(temp_model_registry):
    """Extends the matrix to a model that does not exist in the codebase,
    inside the fixture that keeps the registration from leaking."""
    temp_model_registry.register(
        "qwen3-embed-8b",
        ModelContract(
            model_name="mlx-community/qwen3-embedding-8b",
            vector_dimension=4096,
            model_max_token_length=40960,
            attention_mask_dtype=None,
            compute_dtype_bytes=2,
        ),
    )
    contract = temp_model_registry.get("qwen3-embed-8b")
    for tier in fitting_tiers(contract):
        answers = _answers(model_key="qwen3-embed-8b", tier_key=tier.key)
        config = _build(answers)
        text = dump_config_yaml(config, model_key="qwen3-embed-8b", budget_gb=BUDGET)
        validate_rendered_config(text)


def test_a_watched_config_validates_for_every_fitting_tier():
    """Rules 10 and 11 only fire when watch is enabled."""
    for model_key in ModelRegistry.keys():
        contract = ModelRegistry.get(model_key)
        for tier in fitting_tiers(contract):
            answers = _answers(model_key=model_key, tier_key=tier.key)
            answers.kind.watch_enabled = True
            text = dump_config_yaml(_build(answers), model_key=model_key, budget_gb=BUDGET)
            validate_rendered_config(text)


def test_validate_rejects_an_illegal_engine_name():
    """Rule 6: engine names must be MCP-tool-safe."""
    config = _build(_answers())
    config["engines"]["Bad Name"] = config["engines"].pop("docs")
    text = dump_config_yaml(config, model_key="granite-r2", budget_gb=BUDGET)
    with pytest.raises(ValueError, match="must match"):
        validate_rendered_config(text)


def test_validate_rejects_incoherent_chunk_budgets():
    """Rule 8: chunk_max_tokens must not exceed max_token_length."""
    config = _build(_answers())
    config["profiles"]["docs-medium"]["chunk_max_tokens"] = 99999
    text = dump_config_yaml(config, model_key="granite-r2", budget_gb=BUDGET)
    with pytest.raises(ValueError, match="chunk_max_tokens"):
        validate_rendered_config(text)


def test_a_foreign_project_is_not_a_dbs_vector_checkout(tmp_path):
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname = "some-other-app"\n', encoding="utf-8"
    )
    assert is_dbs_vector_checkout(tmp_path) is False


def test_a_real_checkout_is_recognised(tmp_path):
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "dbs-vector"\n', encoding="utf-8")
    assert is_dbs_vector_checkout(tmp_path) is True


def test_a_nameless_project_is_rejected(tmp_path):
    """What every fixture used to write, and what the old check accepted."""
    (tmp_path / "pyproject.toml").write_text("[project]\n", encoding="utf-8")
    assert is_dbs_vector_checkout(tmp_path) is False


def test_a_missing_or_unparseable_manifest_is_not_a_checkout(tmp_path):
    assert is_dbs_vector_checkout(tmp_path) is False
    (tmp_path / "pyproject.toml").write_text("{ not toml", encoding="utf-8")
    assert is_dbs_vector_checkout(tmp_path) is False
