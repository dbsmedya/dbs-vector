def test_dump_yaml_preserves_key_order_and_carries_a_header():
    config = _build(_answers())
    text = dump_config_yaml(config, model_key="granite-r2", budget_gb=BUDGET)
    assert text.startswith("# Generated by `dbs-vector init`")
    assert "granite-r2" in text
    assert text.index("system:") < text.index("profiles:") < text.index("engines:")


def test_dump_yaml_round_trips():
    config = _build(_answers())
    text = dump_config_yaml(config, model_key="granite-r2", budget_gb=BUDGET)
    assert yaml.safe_load(text) == config


